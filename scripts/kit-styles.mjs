// Copies the shared AI settings styles from src/vendor/rex-ai-kit into styles.css, between markers.
// Run after vendoring a new kit: npm run styles:kit
import { readFileSync, writeFileSync } from 'node:fs';
const START = '/* rex-ai-kit: start (generated by scripts/kit-styles.mjs) */';
const END = '/* rex-ai-kit: end */';
const kit = readFileSync('src/vendor/rex-ai-kit/rex-ai-kit.css', 'utf8').trim();
const css = readFileSync('styles.css', 'utf8');
const block = `${START}\n${kit}\n${END}`;
const i = css.indexOf(START), j = css.indexOf(END);
const next = i >= 0 && j > i ? css.slice(0, i) + block + css.slice(j + END.length) : `${css.trimEnd()}\n\n${block}\n`;
writeFileSync('styles.css', next);
